module m_draw_drv_mif
   use, intrinsic :: iso_fortran_env, only: real32, output_unit, error_unit
   use m_draw_types
   use m_draw_pref
   use m_draw_drivers
   implicit none
   private
   public :: MIF_draw_devcpy, MIF4_draw_devcpy

   real(real32), parameter :: MIFXSIZE0 = 215.0_real32
   real(real32), parameter :: MIFYSIZE0 = 279.0_real32
   real(real32), parameter :: MIFXSIZE  = 190.0_real32
   real(real32), parameter :: MIFYSIZE  = 254.0_real32
   real(real32), parameter :: MIFTORAS  = 20.0_real32
   integer, parameter      :: MAXPOINTS = 1000
   integer, parameter      :: CMAPSIZE  = 256

   type :: rgb_color
      integer :: red = 255, green = 255, blue = 255
   end type rgb_color

   type(rgb_color), save :: MIF_carr(CMAPSIZE)

   ! 1-based translation table between basic draw colors (0..7 -> 1..8) and MIF standard colors
   integer, parameter :: cmap(8) = [1, 2, 3, 7, 4, 6, 5, 0]

   logical, save :: mif_first_time = .true.
   logical, save :: polyopen       = .false.
   integer, save :: points         = 0
   integer, save :: drawn          = 0
   integer, save :: pslstx = -1, pslsty = -1
   integer, save :: MIFVERSION     = 0
   integer, save :: curcol         = 0
   integer, save :: curcol4        = 0
   real(real32), save :: curwid    = 1.0_real32
   integer, save :: groupid        = 1
   integer, save :: curpat         = 0
   real(real32), save :: borderx   = (MIFXSIZE0 - MIFXSIZE) / 2.0_real32
   real(real32), save :: bordery   = (MIFYSIZE0 - MIFYSIZE) / 2.0_real32
   integer, save :: pgroup         = 1
   integer, save :: members        = 0
   real(real32), save :: kludgex   = 0.0_real32, kludgey = 0.0_real32

contains

   subroutine MIF_header()
      character(len=8)  :: dt
      character(len=10) :: tm
      call date_and_time(date=dt, time=tm)

      write(draw_unit, '(A)') "<Comment -"
      write(draw_unit, '(A)') "  Creator: M_DRAW MIF driver"
      write(draw_unit, '(A)') "  Title: Very Ordinary Graphics Learning Environment"
      write(draw_unit, '(A)') "  Author: John S. Urban"
      write(draw_unit, '(A, A, "-", A, "-", A, " ", A, ":", A, ":", A)') &
         "  CreationDate: ", dt(1:4), dt(5:6), dt(7:8), tm(1:2), tm(3:4), tm(5:6)
      write(draw_unit, '(A)') "> # End of <Comment> Statement"
   end subroutine MIF_header

   integer function MIF_mapcolor(i, r, g, b)
      integer, intent(in) :: i, r, g, b
      if (i >= CMAPSIZE .or. i < 0) then
         MIF_mapcolor = -1; return
      end if
      MIF_carr(i + 1)%red   = r
      MIF_carr(i + 1)%green = g
      MIF_carr(i + 1)%blue  = b
      MIF_mapcolor = 0
   end function MIF_mapcolor

   subroutine printcolor(thecolor)
      integer, intent(in) :: thecolor
      integer :: C, M, Y, B

      if (MIFVERSION /= 4) return

      C = (255 - MIF_carr(thecolor + 1)%red)   * 100 / 255
      M = (255 - MIF_carr(thecolor + 1)%green) * 100 / 255
      Y = (255 - MIF_carr(thecolor + 1)%blue)  * 100 / 255
      B = min(C, min(M, Y))
      C = C - B; M = M - B; Y = Y - B

      write(draw_unit, '(A, 4I3.3, A, I0, A, I0, A, I0, A, I0, A, 4I3.3, A)') &
         "<Color <ColorTag " // char(96), C, M, Y, B, "'><ColorCyan ", C, "><ColorMagenta ", M, &
         "><ColorYellow ", Y, "><ColorBlack ", B, ">><ObColor " // char(96), C, M, Y, B, "'>"

   end subroutine printcolor

   integer function MIF_init()
      integer :: prefx, prefy, prefxs, prefys, idum

      draw_unit = draw_outfile()
      if (.not. mif_first_time) then
         MIF_init = 1; return
      end if

      write(draw_unit, '(A, I0, A)') "<MIFFile ", MIFVERSION, ".0> # Generated by M_DRAW driver (John S. Urban, Sept. 1993)"
      write(draw_unit, '(A)') "<Document"
      write(draw_unit, '(A)') "<Units Umm>"
      write(draw_unit, '(A, F0.6, 1X, F0.6, A)') "<DPageSize ", MIFXSIZE0, MIFYSIZE0, " >"
      write(draw_unit, '(A)') "># end of Document"

      call MIF_header()
      write(draw_unit, '(A)') "# MACRO section to reduce file size "
      write(draw_unit, '(A)') "define(P,Point)"
      write(draw_unit, '(A)') "define(S,Separation)"
      write(draw_unit, '(A)') "define(SN,Smoothed No)"
      write(draw_unit, '(A)') "define(PW,PenWidth)"
      write(draw_unit, '(A)') "define(PL,PolyLine)"
      write(draw_unit, '(A)') "define(F,Fill)"
      write(draw_unit, '(A)') "define(GID,GroupID)"
      write(draw_unit, '(A)') "define(G,Group)"
      write(draw_unit, '(A)') "# END MACRO section to reduce file size "
      write(draw_unit, '(A)') "<Page "
      write(draw_unit, '(A, F0.6, 1X, F0.6, A)') "<PageSize ", MIFXSIZE0, MIFYSIZE0, " >"

      call draw_getprefposandsize(prefx, prefy, prefxs, prefys)
      if (prefxs /= -1) then
         vdevice%sizeSy = prefys
         vdevice%sizeSx = prefxs
         vdevice%sizeX  = min(prefys, prefxs); vdevice%sizeY = vdevice%sizeX
         borderx = real(prefx, real32); bordery = real(prefy, real32)
      else
         vdevice%sizeSy = int(MIFYSIZE * MIFTORAS)
         vdevice%sizeSx = int(MIFXSIZE * MIFTORAS)
         vdevice%sizeX  = int(MIFXSIZE * MIFTORAS); vdevice%sizeY = vdevice%sizeX
         borderx = (MIFXSIZE0 - MIFXSIZE) / 2.0_real32
         bordery = (MIFYSIZE0 - MIFYSIZE) / 2.0_real32
      end if

      write(draw_unit, '(A, I0, 1X, I0)') "# ADDRESSABILITY IN RASTERS ", vdevice%sizeSx, vdevice%sizeSy

      MIF_carr = rgb_color(255, 255, 255)
      idum = MIF_mapcolor(0, 255, 255, 255)
      idum = MIF_mapcolor(1, 255,   0,   0)
      idum = MIF_mapcolor(2,   0, 255,   0)
      idum = MIF_mapcolor(3, 255, 255,   0)
      idum = MIF_mapcolor(4,   0,   0, 255)
      idum = MIF_mapcolor(5, 255,   0, 255)
      idum = MIF_mapcolor(6,   0, 255, 255)
      idum = MIF_mapcolor(7,   0,   0,   0)
      idum = MIF_mapcolor(8, 155,   0,   0)
      idum = MIF_mapcolor(9,   0, 155,   0)
      idum = MIF_mapcolor(10, 155, 255, 255)
      idum = MIF_mapcolor(11, 155, 155,   0)
      idum = MIF_mapcolor(12,   0,   0, 155)
      idum = MIF_mapcolor(13, 155,   0, 155)
      idum = MIF_mapcolor(14,   0, 155, 155)
      idum = MIF_mapcolor(15, 100, 100, 100)

      polyopen = .false.; curcol = 0; curcol4 = 0; curwid = 1.0_real32; curpat = 0
      pgroup = groupid; groupid = groupid + 1; drawn = 0
      MIF_init = 1
   end function MIF_init

   subroutine closeline()
      if (polyopen) then
         write(draw_unit, '(A)') "> #end curve PL"
         polyopen = .false.; points = 0
      end if
   end subroutine closeline

   subroutine openline()
      if (.not. polyopen) then
         write(draw_unit, '(A)') "<PL"
         write(draw_unit, '(A, I0, A)') " <GID ", groupid, " >"
         members = members + 1
         write(draw_unit, '(A)') " <SN>"
         write(draw_unit, '(A, F0.6, A)') " <PW ", curwid * real(vdevice%sizeX, real32) / 10000.0_real32 / MIFTORAS, ">"
         write(draw_unit, '(A, I0, A)') " <S ", curcol, " >"
         call printcolor(curcol4)
         write(draw_unit, '(A)') " <F 15 >"
         polyopen = .true.
      end if
   end subroutine openline

   subroutine groupem()
      if (members == 1) then
         write(draw_unit, '(A)') "<PL"
         write(draw_unit, '(A, I0, A)') " <GID ", groupid, " >"
         write(draw_unit, '(A, F0.2, 1X, F0.2, A)') " <P ", kludgex, kludgey, " >"
         write(draw_unit, '(A)') "> #end curve PL"
         write(draw_unit, '(A, I0, A, I0, A)') " <G <ID ", groupid, "> <GID ", pgroup, ">>"
         members = 0; groupid = groupid + 1
      else if (members /= 0) then
         write(draw_unit, '(A, I0, A, I0, A)') " <G <ID ", groupid, "> <GID ", pgroup, ">>"
         members = 0; groupid = groupid + 1
      end if
   end subroutine groupem

   integer function MIF_exit()
      call closeline()
      call groupem()
      write(draw_unit, '(A, I0, A)') " <G <ID ", pgroup, "> >"
      write(draw_unit, '(A)') "> #end of Page"
      write(draw_unit, '(A)') "# End of MIFFile"
      pgroup = groupid; groupid = groupid + 1
      drawn = 0; points = 0
      if (draw_unit /= output_unit .and. draw_unit /= error_unit) then
         flush(draw_unit)
         close(draw_unit)
      end if
      MIF_exit = 0
   end function MIF_exit

   integer function MIF_draw(x, y)
      integer, intent(in) :: x, y
      real(real32) :: realx, realy, realx0, realy0

      realx  = real(x, real32) / MIFTORAS + borderx
      realy  = real(vdevice%sizeSy - y, real32) / MIFTORAS + bordery
      realx0 = real(vdevice%cpVx, real32) / MIFTORAS + borderx
      realy0 = real(vdevice%sizeSy - vdevice%cpVy, real32) / MIFTORAS + bordery

      if (pslstx /= vdevice%cpVx .or. pslsty /= vdevice%cpVy .or. points >= MAXPOINTS) then
         call closeline()
         call openline()
         write(draw_unit, '(A, F0.2, 1X, F0.2, A)') " <P ", realx0, realy0, " >"
         kludgex = realx0; kludgey = realy0; points = 1
      end if
      call openline()
      write(draw_unit, '(A, F0.2, 1X, F0.2, A)') " <P ", realx, realy, " >"
      points = points + 1
      pslstx = x; pslsty = y; drawn = 1
      MIF_draw = 0
   end function MIF_draw

   integer function MIF_clear()
      call closeline()
      if (drawn /= 0) then
         call groupem()
         write(draw_unit, '(A, I0, A)') " <G <ID ", pgroup, "> >"
         write(draw_unit, '(A)') "> #end of Page"
         write(draw_unit, '(A)') "<Page"
         write(draw_unit, '(A, F0.6, 1X, F0.6, A)') "<PageSize  ", MIFXSIZE0, MIFYSIZE0, " >"
         pgroup = groupid; groupid = groupid + 1
      end if
      drawn = 0; points = 0
      MIF_clear = 0
   end function MIF_clear

   integer function MIF_color(col)
      integer, intent(in) :: col
      integer :: c_idx
      call closeline()
      if (col < 0) then
         curwid = real(abs(col), real32)
      else
         curcol4 = mod(col, CMAPSIZE)
         c_idx = mod(col, min(256, CMAPSIZE))
         curcol = cmap(mod(c_idx, 8) + 1)
         if (MIFVERSION == 4) then
            curpat = c_idx / CMAPSIZE
         else
            curpat = c_idx / 16
         end if
      end if
      call groupem()

      MIF_color = 0
   end function MIF_color
   integer function MIF_setlw(width)
      integer, intent(in) :: width
      call closeline()
      curwid = real(abs(width), real32)
      call groupem()
      MIF_setlw = 0
   end function MIF_setlw
   integer function MIF_font(font)
      character(len=*), intent(in) :: font
      if (trim(font) == "small") then
         vdevice%hwidth = 12.0_real32 / 72.0_real32 / 0.03937_real32 * MIFTORAS
         vdevice%hheight = vdevice%hwidth * 2.2_real32
      else if (trim(font) == "large") then
         vdevice%hheight = 55.0_real32 / 72.0_real32 / 0.03937_real32 * MIFTORAS
         vdevice%hwidth = vdevice%hheight / 4.5_real32
      else
         MIF_font = 0; return
      end if
      MIF_font = 1
   end function MIF_font
   integer function MIF_string(s)
      character(len=*), intent(in) :: s
      real(real32) :: realy0, realx0
      integer :: i
      character(len=1) :: c
      realy0 = real(vdevice%sizeSy - vdevice%cpVy, real32) / MIFTORAS + bordery
      realx0 = real(vdevice%cpVx, real32) / MIFTORAS + bordery
      call closeline()
      write(draw_unit, '(A)') "<TextLine "
      write(draw_unit, '(A, I0, A)') " <GID ", groupid, " >"
      members = members + 1
      write(draw_unit, '(A, I0, A)') " <F ", curpat, " >"
      write(draw_unit, '(A, F0.6, 2X, F0.6, A)') " <TLOrigin ", realx0, realy0, " > "
      kludgex = realx0; kludgey = realy0
      write(draw_unit, '(A)') " <Font "
      write(draw_unit, '(A)') " <FFamily `Courier'> "
      write(draw_unit, '(A, F0.6, A)') " <FSize ", vdevice%hheight / MIFTORAS, " > "
      write(draw_unit, '(A)') " "
      write(draw_unit, '(A)') " "
      write(draw_unit, '(A, I0, A)') " <FSeparation ", curcol, " > "
      write(draw_unit, '(A)') " > # end Font "

      write(draw_unit, '(A)', advance='no') "<String " // char(96)
      do i = 1, len(s)
         c = s(i:i)
         select case (c)
         case ('\')
            write(draw_unit, '(A)', advance='no') "\\"
         case (char(96))
            write(draw_unit, '(A)', advance='no') "\Q"
         case ('>')
            write(draw_unit, '(A)', advance='no') "\>"
         case ("'")
            write(draw_unit, '(A)', advance='no') "\q"
         case default
            write(draw_unit, '(A)', advance='no') c
         end select
      end do
      write(draw_unit, '(A, /, A, A, A)') "'> ", "> # end TextLine [", trim(s), "] "

      drawn = 1; pslstx = -1; pslsty = -1
      MIF_string = 0

end function MIF_string

integer function MIF_char(c)
   character(len=1), intent(in) :: c
   integer :: idum
   idum = MIF_string(c)
   MIF_char = 0
end function MIF_char
integer function MIF_fill(n, x, y)
   integer, intent(in) :: n
   integer, intent(in) :: x(n), y(n)
   integer :: i
   real(real32) :: realx, realy
   call closeline()
   write(draw_unit, '(A)') "<Polygon "
   write(draw_unit, '(A, I0, A)') " <GID ", groupid, " >"
   members = members + 1
   write(draw_unit, '(A, F0.6, A)') " <PW ", real(vdevice%sizeX, real32) * curwid / 10000.0_real32 / MIFTORAS, ">"
   write(draw_unit, '(A, I0, A)') " <S ", curcol, " >"
   call printcolor(curcol4)
   write(draw_unit, '(A, I0, A)') " <F ", curpat, " >"
   kludgex = real(x(1), real32) / MIFTORAS + borderx
   kludgey = real(vdevice%sizeSy - y(1), real32) / MIFTORAS + bordery
   do i = 1, n
      realx = real(x(i), real32) / MIFTORAS + borderx
      realy = real(vdevice%sizeSy - y(i), real32) / MIFTORAS + bordery
      write(draw_unit, '(A, F0.2, 1X, F0.2, A)') " <P ", realx, realy, " >"
   end do
   write(draw_unit, '(A)') "> #end of Polygon "
   vdevice%cpVx = x(n); vdevice%cpVy = y(n)
   pslstx = -1; pslsty = -1; drawn = 1
   MIF_fill = 0
end function MIF_fill

integer function noop(); noop = -1; end function

integer function noop2(x, y); integer, intent(out) :: x, y; x = 0; y = 0; noop2 = -1; end function

subroutine setup_mifdev()
   vdevice%dev%devname = "mif"
   vdevice%dev%large = "large"
   vdevice%dev%small = "small"
   vdevice%dev%Vbackb => noop
   vdevice%dev%Vchar => MIF_char
   vdevice%dev%Vcheckkey => noop
   vdevice%dev%Vclear => MIF_clear
   vdevice%dev%Vcolor => MIF_color
   vdevice%dev%Vdraw => MIF_draw
   vdevice%dev%Vexit => MIF_exit
   vdevice%dev%Vfill => MIF_fill
   vdevice%dev%Vfont => MIF_font
   vdevice%dev%Vfrontb => noop
   vdevice%dev%Vgetkey => noop
   vdevice%dev%Vinit => MIF_init
   vdevice%dev%Vlocator => noop2
   vdevice%dev%Vmapcolor => MIF_mapcolor
   vdevice%dev%Vsetlw => MIF_setlw
   vdevice%dev%Vstring => MIF_string
   vdevice%dev%Vswapb => noop
   vdevice%dev%Vsync => noop
end subroutine setup_mifdev

integer function MIF_draw_devcpy()
   call setup_mifdev(); MIFVERSION = 3; vdevice%depth = 3; MIF_draw_devcpy = 0
end function MIF_draw_devcpy

integer function MIF4_draw_devcpy()
   call setup_mifdev(); MIFVERSION = 4; vdevice%depth = 8; MIF4_draw_devcpy = 0
end function MIF4_draw_devcpy

end module m_draw_drv_mif
